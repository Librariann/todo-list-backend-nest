BEGIN;

CREATE TABLE IF NOT EXISTS todo_list.ai_recommendation_states (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES todo_list.users(id) ON DELETE CASCADE,
  generation_date date,
  attempts integer NOT NULL DEFAULT 0,
  last_attempt_at timestamptz,
  lease_until timestamptz,
  lease_token uuid,
  latest_generation_id uuid,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_ai_recommendation_states_user UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS todo_list.ai_recommendations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES todo_list.users(id) ON DELETE CASCADE,
  generation_id uuid NOT NULL,
  type varchar(10) NOT NULL,
  title varchar(50) NOT NULL,
  reason varchar(300) NOT NULL,
  payload jsonb NOT NULL,
  source_ids jsonb NOT NULL,
  status varchar NOT NULL DEFAULT 'PENDING',
  created_item_id bigint,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_recommendations_user_generation
  ON todo_list.ai_recommendations(user_id, generation_id);

COMMIT;
